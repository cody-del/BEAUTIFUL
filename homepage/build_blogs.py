def image_for(post):
    return ASSETS.get(post['image'].get('src'), FALLBACK_IMAGES.get(post['slug']))


def strip_text(html):
    class Text(HTMLParser):
        def __init__(self):
            super().__init__(convert_charrefs=True)
            self.parts = []
        def handle_data(self, text):
            self.parts.append(text)
    parser = Text()
    parser.feed(html)
    return ' '.join(''.join(parser.parts).split())


def article_body(post):
    body = post['source_html']
    # Preserve the words in the additional source H1; correct its structural level.
    body = re.sub(r'<(/?)h1\b', r'<\1h2', body)
    def href(match):
        value = unescape(match[1])
        path = value.removeprefix(LIVE)
        if path == '/shades/cellular-shades':
            path = '/custom-shades-fort-wayne-indiana/cellular-shades-fort-wayne-indiana'
        # Existing contact-ghl remains on the live site until that route is migrated.
        if path.startswith('/') and not path.startswith('//'):
            if path.split('#')[0].rstrip('/') in BUILT or path == '/':
                value = path
            else:
                value = LIVE + path
        return 'href="' + escape(value, quote=True) + '"'
    body = re.sub(r'href="([^"]*)"', href, body)
    def img(match):
        tag = match[0]
        for remote, local in ASSETS.items():
            tag = tag.replace(remote, local)
        tag = re.sub(r'\s(?:srcset|sizes|width|height)="[^"]*"', '', tag)
        if 'loading=' not in tag:
            tag = tag.replace('<img', '<img loading="lazy"')
        return tag
    body = re.sub(r'<img\b[^>]*>', img, body)
    headings = []
    def heading(match):
        level, attrs, words = match.groups()
        anchor = 'guide-section-' + str(len(headings) + 1)
        headings.append((int(level), anchor, strip_text(words)))
        attrs = re.sub(r'\s+id="[^"]*"', '', attrs)
        return f'<h{level}{attrs} id="{anchor}">{words}</h{level}>'
    body = re.sub(r'<h([2-6])([^>]*)>(.*?)</h\1>', heading, body, flags=re.S)
    assert strip_text(body) == post['source_text'], 'Article wording changed: ' + post['slug']
    return body, headings


