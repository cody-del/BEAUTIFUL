def shared_paths(html):
    html = html.replace('src="assets/', 'src="/assets/').replace('href="./"', 'href="/"')
    return re.sub(r'href="#(products|meet-david|service-area|reviews|guides)"', r'href="/#\1"', html).replace('href="#consultation"','href="/contact"')


def shell(home, title, description, path, content, schema, image=None):
    head = home[home.index('<head>'):home.index('</head>') + len('</head>')]
    head = re.sub(r'<title>.*?</title>', '<title>' + escape(title) + '</title>', head)
    head = re.sub(r'<meta name="description"[^>]+>', '<meta name="description" content="' + escape(description, quote=True) + '">', head)
    head = head.replace('rel="canonical" href="' + LIVE + '/"', 'rel="canonical" href="' + LIVE + path + '"')
    head = re.sub(r'\s*<link rel="preload"[^>]*>', '', head)
    head = head.replace('href="assets/', 'href="/assets/').replace('href="styles.css', 'href="/styles.css').replace('src="script.js', 'src="/script.js')
    social = f'<meta property="og:type" content="{"article" if path.startswith("/blog-post/") else "website"}"><meta property="og:title" content="{escape(title,quote=True)}"><meta property="og:description" content="{escape(description,quote=True)}"><meta property="og:url" content="{LIVE + path}">'
    if image:
        social += '<meta property="og:image" content="' + LIVE + image + '">'
    head = head.replace('</head>', social + '\n<script type="application/ld+json">' + json.dumps(schema).replace('</','<\\/') + '</script>\n</head>')
    header = shared_paths(home[home.index('  <header class="header">'):home.index('  <main')])
    footer = shared_paths(home[home.index('  <footer class="footer">'):])
    return '<!doctype html>\n<html lang="en">\n' + head + '\n<body class="blog-page"><a class="skip" href="#main">Skip to content</a>\n' + header + '<main id="main">\n' + content + '\n</main>\n' + footer


